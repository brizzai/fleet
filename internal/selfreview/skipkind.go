package selfreview

import (
	"fmt"
	"path"
	"strings"
)

// Skip kinds the model may give a "by guide" skip. Each but mechanical names a
// class of file, and Enforce holds the kind to the path: a skip calling a
// Python module "docs" is not believed.
const (
	SkipMechanical = "mechanical" // renames, moves, formatting, import churn: no behaviour change
	SkipDocs       = "docs"
	SkipFixture    = "fixture"
	SkipConfig     = "config"
	SkipGenerated  = "generated"
)

var skipKinds = []string{SkipMechanical, SkipDocs, SkipFixture, SkipConfig, SkipGenerated}

// Size rules for a guide skip of a source file — one that is none of docs,
// fixture, config or generated by the path rules below. The failure they exist
// for was real: a reviewer skipped 152 changed lines of ingestion logic as
// "covered by tests", and fleet showed it as settled.
const (
	// SourceSkipMinLines is where a source file stops being skippable for any
	// reason but "mechanical".
	SourceSkipMinLines = 30
	// MechanicalMaxLines caps "mechanical": past it, nobody can honestly say
	// a change has no behaviour in it without reading it.
	MechanicalMaxLines = 80
)

// fileClass is the class a path belongs to by fleet's own rules, or "" for a
// source file. A path can match more than one predicate (a JSON fixture is
// also a config-shaped file); kindFits checks the one the model claimed.
func fileClass(p string) string {
	for _, k := range []string{SkipGenerated, SkipFixture, SkipDocs, SkipConfig} {
		if kindFits(k, p) {
			return k
		}
	}
	return ""
}

// kindFits reports whether a skip kind is believable for the path.
func kindFits(kind, p string) bool {
	switch kind {
	case SkipMechanical:
		return true
	case SkipDocs:
		return isDocPath(p)
	case SkipFixture:
		return isFixturePath(p)
	case SkipConfig:
		return isConfigPath(p)
	case SkipGenerated:
		return isGeneratedPath(p)
	}
	return false
}

func lowerParts(p string) (dirs []string, base, ext string) {
	p = strings.ToLower(strings.TrimPrefix(path.Clean(strings.ReplaceAll(p, `\`, "/")), "./"))
	base = path.Base(p)
	if d := path.Dir(p); d != "." {
		dirs = strings.Split(d, "/")
	}
	return dirs, base, path.Ext(base)
}

func hasDir(dirs []string, names ...string) bool {
	for _, d := range dirs {
		for _, n := range names {
			if d == n {
				return true
			}
		}
	}
	return false
}

func isDocPath(p string) bool {
	dirs, _, ext := lowerParts(p)
	switch ext {
	case ".md", ".mdx", ".rst", ".txt":
		return true
	}
	return hasDir(dirs, "docs", "doc")
}

func isFixturePath(p string) bool {
	dirs, base, ext := lowerParts(p)
	if hasDir(dirs, "testdata", "fixtures", "fixture", "test_data", "__snapshots__") || strings.HasSuffix(base, ".snap") {
		return true
	}
	switch ext {
	case ".json", ".yaml", ".yml", ".csv":
		return hasDir(dirs, "test", "tests", "__tests__", "spec", "specs")
	}
	return false
}

func isConfigPath(p string) bool {
	_, base, ext := lowerParts(p)
	switch ext {
	case ".yaml", ".yml", ".toml", ".ini", ".cfg", ".json", ".conf":
		return true
	}
	return strings.HasSuffix(base, ".env.example") || base == ".env.example" ||
		base == "dockerfile" || strings.HasPrefix(base, "dockerfile.") || strings.HasSuffix(base, ".dockerfile") ||
		base == "makefile" || strings.HasSuffix(base, ".mk")
}

// isGeneratedPath follows the conventions the diff classifier uses
// (internal/review.ClassifyPath), restated here because this package imports
// no diff engine.
func isGeneratedPath(p string) bool {
	dirs, base, _ := lowerParts(p)
	for _, suf := range []string{".pb.go", "_pb2.py", "_pb2.pyi", ".pb.cc", ".pb.h", "_generated.go",
		".gen.go", ".g.dart", ".freezed.dart", ".designer.cs", ".min.js", ".min.css"} {
		if strings.HasSuffix(base, suf) {
			return true
		}
	}
	return hasDir(dirs, "generated", "__generated__", "gen")
}

// skipRefusal is fleet's reason for refusing a guide skip, or "" when the skip
// stands. lines is what the skip claims: the whole file for scope "file", the
// lines outside every stop for scope "rest". The reason is shown on the Not
// covered card, so it quotes what the reviewer said and states the number.
func skipRefusal(s Skip, p string, lines int) string {
	said := skipSaid(s)
	class := fileClass(p)
	if s.Kind != "" && !kindFits(s.Kind, p) && lines > SmallSkipMaxLines {
		return fmt.Sprintf("%s (%s), but it is not a %s file", said, s.Kind, kindNoun(s.Kind))
	}
	if s.Kind == SkipMechanical && lines >= MechanicalMaxLines {
		return fmt.Sprintf("%s (mechanical) — %d changed lines is too many to skip unread", said, lines)
	}
	if class == "" && s.Kind != SkipMechanical && lines >= SourceSkipMinLines {
		return fmt.Sprintf("%s — %d changed lines of logic", said, lines)
	}
	return ""
}

// skipSaid is how a refusal quotes the skip: "skipped as 'covered by tests'".
func skipSaid(s Skip) string {
	if r := strings.TrimRight(cleanLine(s.Reason), ".…"); r != "" {
		return fmt.Sprintf("skipped as '%s'", r)
	}
	return "skipped"
}

// highRiskRefusal is the Not covered reason for a guide skip of a high-risk
// path.
func highRiskRefusal(s Skip) string { return skipSaid(s) + ", but it is a high-risk path" }

func kindNoun(kind string) string {
	switch kind {
	case SkipDocs:
		return "doc"
	case SkipFixture:
		return "test-data"
	}
	return kind
}
